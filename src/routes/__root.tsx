function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  // Sessions signed with a retired key fail server checks ("No suitable key").
  // Detect them on load and refresh, or sign out if refresh fails.
  useEffect(() => {
    (async () => {
      const { data } = await supabase.auth.getSession();
      const token = data.session?.access_token;
      if (!token) return;
      try {
        const encoded = token.split(".")[0];
        if (!encoded) return;
        const header = JSON.parse(atob(encoded.replace(/-/g, "+").replace(/_/g, "/")));
        const jwks = await (
          await fetch(`${import.meta.env["VITE_SUPABASE_URL"]}/auth/v1/.well-known/jwks.json`)
        ).json();
        const known = (jwks.keys ?? []).some((k: { kid?: string }) => k.kid === header.kid);
        if (header.alg !== "HS256" && !known) {
          const r = await supabase.auth.refreshSession();
          if (r.error) await supabase.auth.signOut();
        }
      } catch {
        /* ignore malformed tokens; server will reject */
      }
    })();
  }, []);
  useEffect(() => {
    const { data } = supabase.auth.onAuthStateChange((event) => {
      if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
      router.invalidate();
      if (event !== "SIGNED_OUT") queryClient.invalidateQueries();
      if (event === "SIGNED_IN" && !sessionStorage.getItem("gx-welcome")) {
        sessionStorage.setItem("gx-welcome", "1");
        void import("@/lib/email.functions").then((m) => m.sendWelcomeEmail()).catch(() => {});
      }
    });
    return () => data.subscription.unsubscribe();
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      <Outlet />
      <Toaster position="top-center" richColors />
    </QueryClientProvider>
  );
}
